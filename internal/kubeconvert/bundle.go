package kubeconvert

import (
	"archive/zip"
	"encoding/json"
	"io"
	"path"
	"time"
)

// Bundle writes a revision as a ZIP: its files under one folder named after the conversion and a samuori-review.json
// with its findings and lineage. Revisions never hold credentials: post-processing removed literal secret values.
func Bundle(w io.Writer, name string, rev Revision) error {
	z := zip.NewWriter(w)
	mod := rev.CreatedAt.UTC()
	if mod.IsZero() {
		mod = time.Unix(0, 0).UTC()
	}
	put := func(p string, b []byte) error {
		f, err := z.CreateHeader(&zip.FileHeader{Name: path.Join(name, p), Method: zip.Deflate, Modified: mod})
		if err != nil {
			return err
		}
		_, err = f.Write(b)
		return err
	}
	for _, f := range rev.Files {
		if err := put(f.Path, []byte(f.Content)); err != nil {
			return err
		}
	}
	review, _ := json.MarshalIndent(struct {
		Revision int       `json:"revision"`
		Findings []Finding `json:"findings"`
		Lineage  Lineage   `json:"lineage"`
		Note     string    `json:"note"`
	}{rev.Number, rev.Findings, rev.Lineage, "Generated by Samuori for review. Samuori never applies these files to a cluster."}, "", "  ")
	if err := put("samuori-review.json", append(review, '\n')); err != nil {
		return err
	}
	return z.Close()
}
