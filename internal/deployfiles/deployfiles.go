// Package deployfiles writes starting Compose files and Helm charts that reference a built image (ADR 0059). The
// files carry references and port, probe and placeholder settings from the BuildSpec, never secret values.
package deployfiles

import (
	"archive/tar"
	"bytes"
	"compress/gzip"
	"encoding/json"
	"fmt"
	"io"
	"regexp"
	"strconv"
	"strings"
	"time"

	"samuori.invalid/samuori/internal/buildspec"
)

// Image is the reference the files use: a publication's registry location pinned by digest, or the local name
// docker load gives the downloaded archive.
type Image struct {
	Repository string
	Tag        string
	// Digest is the manifest digest a publication recorded; empty for a local image.
	Digest    string
	Published bool
}

func (i Image) Reference() string {
	ref := i.Repository
	if i.Tag != "" {
		ref += ":" + i.Tag
	}
	if i.Digest != "" {
		ref += "@" + i.Digest
	}
	return ref
}

type Input struct {
	Name, Version string
	App           *buildspec.Application
	Image         Image
	// ModTime stamps archive entries, so the same build always yields the same bytes.
	ModTime time.Time
}

type File struct {
	Path    string
	Content []byte
}

var (
	slugUnsafe = regexp.MustCompile(`[^a-z0-9]+`)
	dailyVer   = regexp.MustCompile(`^(\d{4})-(\d{2})-(\d{2})\.(\d+)$`)
	metaUnsafe = regexp.MustCompile(`[^0-9A-Za-z.-]+`)
	metaDots   = regexp.MustCompile(`\.{2,}`)
)

// Slug is a name Compose services, Helm charts and Kubernetes labels all accept.
func Slug(name string) string {
	s := strings.Trim(slugUnsafe.ReplaceAllString(strings.ToLower(name), "-"), "-")
	if len(s) > 53 {
		s = strings.TrimRight(s[:53], "-")
	}
	if s == "" {
		return "app"
	}
	return s
}

// ChartVersion turns a build version such as 2026-10-27.3 into the semver 2026.1027.3, which keeps builds in order;
// any other version becomes build metadata of 0.1.0.
func ChartVersion(version string) string {
	if m := dailyVer.FindStringSubmatch(version); m != nil {
		y, _ := strconv.Atoi(m[1])
		mo, _ := strconv.Atoi(m[2])
		d, _ := strconv.Atoi(m[3])
		n, _ := strconv.Atoi(m[4])
		return fmt.Sprintf("%d.%d.%d", y, mo*100+d, n)
	}
	meta := strings.Trim(metaDots.ReplaceAllString(metaUnsafe.ReplaceAllString(version, "-"), "."), ".")
	if meta == "" {
		return "0.1.0"
	}
	return "0.1.0+" + meta
}

func (in Input) appType() string {
	if in.App == nil {
		return ""
	}
	return in.App.Type
}

// serves reports whether the image listens on a port others reach; workers and command-line tasks do not.
func (in Input) serves() bool {
	t := in.appType()
	return in.App != nil && in.App.Port > 0 && t != "worker" && t != "cli-task"
}

func (in Input) httpProbe() bool {
	return in.serves() && in.App.HealthPath != "" && in.appType() != "database"
}

func (in Input) job() bool { return in.appType() == "cli-task" }

func q(s string) string {
	b, _ := json.Marshal(s)
	return string(b)
}

func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }

func (in Input) header(kind string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Starting %s for %s %s, generated by Samuori. Review it before use; Samuori does not deploy anything.\n", kind, oneLine(in.Name), oneLine(in.Version))
	if in.Image.Published {
		fmt.Fprintf(&b, "# The image is published at %s with tag %s and pinned to digest %s.\n", in.Image.Repository, in.Image.Tag, in.Image.Digest)
	} else {
		fmt.Fprintf(&b, "# The image is not published to a registry. Download it from Samuori and load it first (docker load -i <file>.tar);\n# it is then named %s.\n", in.Image.Reference())
	}
	return b.String()
}

// Compose is a compose.yml with one service running the image.
func Compose(in Input) []byte {
	var b strings.Builder
	b.WriteString(in.header("Compose file"))
	name := Slug(in.Name)
	fmt.Fprintf(&b, "services:\n  %s:\n    image: %s\n", name, q(in.Image.Reference()))
	if !in.Image.Published {
		b.WriteString("    pull_policy: never\n")
	}
	if in.job() {
		b.WriteString("    restart: \"no\"\n")
	} else {
		b.WriteString("    restart: unless-stopped\n")
	}
	if in.serves() {
		fmt.Fprintf(&b, "    ports:\n      - %s\n", q(fmt.Sprintf("%d:%d", in.App.Port, in.App.Port)))
		if in.httpProbe() {
			fmt.Fprintf(&b, "    # No healthcheck: Compose runs it inside the container and Samuori cannot assume the image has curl or wget.\n    # The application answers %s on port %d.\n", in.App.HealthPath, in.App.Port)
		}
	}
	b.WriteString("    # The BuildSpec declares no runtime environment variables; add the ones the application reads.\n" +
		"    # environment:\n    #   NAME: \"\"\n" +
		"    # Keep secret values out of this file, for example in an env file that is not committed.\n" +
		"    # env_file: .env\n")
	return []byte(b.String())
}

// Chart is a Helm chart's files under <name>/, in a fixed order.
func Chart(in Input) []File {
	name := Slug(in.Name)
	chart := fmt.Sprintf("apiVersion: v2\nname: %s\ndescription: %s\ntype: application\nversion: %s\nappVersion: %s\n",
		name, q("Starting chart for "+in.Name+", generated by Samuori. Review it before use."), ChartVersion(in.Version), q(in.Version))
	files := []File{
		{name + "/Chart.yaml", []byte(chart)},
		{name + "/values.yaml", []byte(in.values())},
		{name + "/templates/_helpers.tpl", []byte(helpers(name))},
	}
	if in.job() {
		files = append(files, File{name + "/templates/job.yml", []byte(in.workload(name, "Job"))})
	} else {
		files = append(files, File{name + "/templates/deployment.yml", []byte(in.workload(name, "Deployment"))})
	}
	if in.serves() {
		files = append(files, File{name + "/templates/service.yml", []byte(service(name))})
	}
	files = append(files, File{name + "/templates/NOTES.txt", []byte(in.notes(name))})
	return files
}

func (in Input) values() string {
	var b strings.Builder
	b.WriteString(in.header("Helm values"))
	pull := "IfNotPresent"
	if !in.Image.Published {
		pull = "Never"
		b.WriteString("# Kubernetes nodes need the image loaded, for example with kind load image-archive or ctr -n k8s.io images import.\n" +
			"# pullPolicy Never keeps the node from pulling a different image of the same name from a public registry.\n")
	}
	fmt.Fprintf(&b, "image:\n  repository: %s\n  tag: %s\n  digest: %s\n  pullPolicy: %s\n", q(in.Image.Repository), q(in.Image.Tag), q(in.Image.Digest), pull)
	b.WriteString("# Names of existing Secrets holding registry credentials, if the registry needs them.\nimagePullSecrets: []\n")
	if !in.job() {
		b.WriteString("replicaCount: 1\n")
	}
	if in.serves() {
		fmt.Fprintf(&b, "containerPort: %d\nservice:\n  type: ClusterIP\n  port: %d\n", in.App.Port, in.App.Port)
	}
	if in.httpProbe() {
		fmt.Fprintf(&b, "probes:\n  path: %s\n", q(in.App.HealthPath))
	}
	b.WriteString("# The BuildSpec declares no runtime environment variables; add the ones the application reads, such as:\n" +
		"# - name: NAME\n#   value: \"\"\nenv: []\n" +
		"# Name of an existing Secret whose keys become environment variables. Samuori never puts secret values here.\n" +
		"existingSecret: \"\"\n" +
		"# The BuildSpec sets no resource requests or limits; set them for your cluster.\nresources: {}\n")
	return b.String()
}

func helpers(name string) string {
	return fmt.Sprintf(`{{- define "%[1]s.fullname" -}}
{{- .Release.Name | trunc 63 | trimSuffix "-" -}}
{{- end -}}

{{- define "%[1]s.selectorLabels" -}}
app.kubernetes.io/name: {{ .Chart.Name }}
app.kubernetes.io/instance: {{ .Release.Name }}
{{- end -}}

{{- define "%[1]s.labels" -}}
{{ include "%[1]s.selectorLabels" . }}
app.kubernetes.io/version: {{ .Chart.AppVersion | quote }}
app.kubernetes.io/managed-by: {{ .Release.Service }}
{{- end -}}

{{- define "%[1]s.image" -}}
{{ .Values.image.repository }}{{ with .Values.image.tag }}:{{ . }}{{ end }}{{ with .Values.image.digest }}@{{ . }}{{ end }}
{{- end -}}
`, name)
}

func (in Input) workload(name, kind string) string {
	var b strings.Builder
	api := "apps/v1"
	if kind == "Job" {
		api = "batch/v1"
	}
	fmt.Fprintf(&b, `apiVersion: %[2]s
kind: %[3]s
metadata:
  name: {{ include "%[1]s.fullname" . }}
  labels:
    {{- include "%[1]s.labels" . | nindent 4 }}
spec:
`, name, api, kind)
	if kind == "Deployment" {
		fmt.Fprintf(&b, `  replicas: {{ .Values.replicaCount }}
  selector:
    matchLabels:
      {{- include "%[1]s.selectorLabels" . | nindent 6 }}
`, name)
	}
	fmt.Fprintf(&b, `  template:
    metadata:
      labels:
        {{- include "%[1]s.selectorLabels" . | nindent 8 }}
    spec:
`, name)
	if kind == "Job" {
		b.WriteString("      restartPolicy: Never\n")
	}
	fmt.Fprintf(&b, `      {{- with .Values.imagePullSecrets }}
      imagePullSecrets:
        {{- range . }}
        - name: {{ . | quote }}
        {{- end }}
      {{- end }}
      containers:
        - name: {{ .Chart.Name }}
          image: {{ include "%[1]s.image" . | quote }}
          imagePullPolicy: {{ .Values.image.pullPolicy }}
`, name)
	if in.serves() {
		b.WriteString(`          ports:
            - name: app
              containerPort: {{ .Values.containerPort }}
              protocol: TCP
`)
	}
	if in.httpProbe() {
		for _, p := range []string{"livenessProbe", "readinessProbe"} {
			fmt.Fprintf(&b, `          %s:
            httpGet:
              path: {{ .Values.probes.path | quote }}
              port: app
`, p)
		}
	}
	b.WriteString(`          {{- with .Values.env }}
          env:
            {{- toYaml . | nindent 12 }}
          {{- end }}
          {{- with .Values.existingSecret }}
          envFrom:
            - secretRef:
                name: {{ . | quote }}
          {{- end }}
          {{- with .Values.resources }}
          resources:
            {{- toYaml . | nindent 12 }}
          {{- end }}
`)
	return b.String()
}

func service(name string) string {
	return fmt.Sprintf(`apiVersion: v1
kind: Service
metadata:
  name: {{ include "%[1]s.fullname" . }}
  labels:
    {{- include "%[1]s.labels" . | nindent 4 }}
spec:
  type: {{ .Values.service.type }}
  selector:
    {{- include "%[1]s.selectorLabels" . | nindent 4 }}
  ports:
    - name: app
      port: {{ .Values.service.port }}
      targetPort: app
      protocol: TCP
`, name)
}

func (in Input) notes(name string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "%s runs image {{ include %q . }}.\n", name, name+".image")
	if !in.Image.Published {
		b.WriteString("The image is not in a registry: load it into the cluster's nodes before installing.\n")
	}
	if in.serves() {
		fmt.Fprintf(&b, "To reach it from this machine:\n  kubectl port-forward --namespace {{ .Release.Namespace }} service/{{ include %q . }} %d:{{ .Values.service.port }}\n", name+".fullname", in.App.Port)
	}
	return b.String()
}

// WriteChart writes the chart as the .tgz archive helm package produces.
func WriteChart(w io.Writer, in Input) error {
	zw, err := gzip.NewWriterLevel(w, gzip.BestCompression)
	if err != nil {
		return err
	}
	at := in.ModTime.UTC().Truncate(time.Second)
	zw.ModTime = at
	tw := tar.NewWriter(zw)
	for _, f := range Chart(in) {
		if err := tw.WriteHeader(&tar.Header{Name: f.Path, Mode: 0o644, Size: int64(len(f.Content)), ModTime: at, Typeflag: tar.TypeReg}); err != nil {
			return err
		}
		if _, err := io.Copy(tw, bytes.NewReader(f.Content)); err != nil {
			return err
		}
	}
	if err := tw.Close(); err != nil {
		return err
	}
	return zw.Close()
}

// ChartFilename is the archive name helm package would give the chart.
func ChartFilename(in Input) string {
	return Slug(in.Name) + "-" + ChartVersion(in.Version) + ".tgz"
}
