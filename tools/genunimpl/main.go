// Command genunimpl emits 501 stubs for every method of the generated ServerInterface.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"log"
	"os"
)

func main() {
	in := flag.String("in", "", "generated server file")
	out := flag.String("out", "", "output file")
	flag.Parse()

	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, *in, nil, 0)
	if err != nil {
		log.Fatal(err)
	}
	var methods []*ast.Field
	ast.Inspect(f, func(n ast.Node) bool {
		ts, ok := n.(*ast.TypeSpec)
		if !ok || ts.Name.Name != "ServerInterface" {
			return true
		}
		methods = ts.Type.(*ast.InterfaceType).Methods.List
		return false
	})
	if len(methods) == 0 {
		log.Fatal("ServerInterface not found")
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by tools/genunimpl. DO NOT EDIT.\n\npackage %s\n\nimport \"net/http\"\n\n", f.Name.Name)
	b.WriteString("// Unimplemented answers 501 for every operation; embed it and override operations as they are built.\ntype Unimplemented struct{}\n\n")
	b.WriteString("var _ ServerInterface = Unimplemented{}\n\n")
	for _, m := range methods {
		ft := m.Type.(*ast.FuncType)
		var params bytes.Buffer
		for i, p := range ft.Params.List {
			if i > 0 {
				params.WriteString(", ")
			}
			name := "_"
			if i == 0 {
				name = "w"
			} else if i == 1 {
				name = "r"
			}
			for j := range p.Names {
				if j > 0 {
					params.WriteString(", ")
				}
				params.WriteString(name)
			}
			params.WriteString(" ")
			if err := printer.Fprint(&params, fset, p.Type); err != nil {
				log.Fatal(err)
			}
		}
		fmt.Fprintf(&b, "func (Unimplemented) %s(%s) { NotImplemented(w, r, %q) }\n\n", m.Names[0].Name, params.String(), m.Names[0].Name)
	}
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}
