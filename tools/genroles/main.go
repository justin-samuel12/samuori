// Command genroles writes the UI's operation → roles table from the x-samuori-roles and x-samuori-public extensions the
// server enforces (internal/api/middleware.go), so the UI never keeps its own role lists.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"log"
	"os"
	"sort"
	"strings"

	"github.com/getkin/kin-openapi/openapi3"
)

func main() {
	in := flag.String("spec", "api/openapi/samuori.v1.yml", "OpenAPI document")
	out := flag.String("out", "ui/src/api/generated/roles.ts", "output file")
	flag.Parse()
	spec, err := openapi3.NewLoader().LoadFromFile(*in)
	if err != nil {
		log.Fatal(err)
	}
	src, err := render(spec)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// access mirrors the server: public skips authentication, "any" admits every signed-in principal, otherwise one of
// the roles is needed. An operation that declares neither is open to no one.
func access(op *openapi3.Operation) (string, error) {
	if op.Extensions["x-samuori-public"] == true {
		return `"public"`, nil
	}
	raw, _ := op.Extensions["x-samuori-roles"].([]any)
	roles := make([]string, 0, len(raw))
	for _, v := range raw {
		s, ok := v.(string)
		if !ok {
			return "", fmt.Errorf("x-samuori-roles holds %v", v)
		}
		if s == "any" {
			return `"any"`, nil
		}
		roles = append(roles, fmt.Sprintf("%q", s))
	}
	return "[" + strings.Join(roles, ", ") + "]", nil
}

func render(spec *openapi3.T) ([]byte, error) {
	lines := map[string]string{}
	for _, item := range spec.Paths.Map() {
		for _, op := range item.Operations() {
			if op.OperationID == "" {
				continue
			}
			if _, dup := lines[op.OperationID]; dup {
				return nil, fmt.Errorf("operationId %s is used twice", op.OperationID)
			}
			a, err := access(op)
			if err != nil {
				return nil, fmt.Errorf("%s: %w", op.OperationID, err)
			}
			lines[op.OperationID] = a
		}
	}
	ids := make([]string, 0, len(lines))
	for id := range lines {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	var b bytes.Buffer
	b.WriteString("// Generated by tools/genroles from api/openapi/samuori.v1.yml (x-samuori-roles, x-samuori-public). Do not edit.\n")
	b.WriteString("// The server authorizes every call; this table only lets the UI hide what would be refused.\n\n")
	b.WriteString("export type Access = \"public\" | \"any\" | readonly string[];\n\n")
	b.WriteString("export const operationAccess = {\n")
	for _, id := range ids {
		fmt.Fprintf(&b, "  %s: %s,\n", id, lines[id])
	}
	b.WriteString("} as const satisfies Record<string, Access>;\n\n")
	b.WriteString("export type OperationId = keyof typeof operationAccess;\n")
	return b.Bytes(), nil
}
