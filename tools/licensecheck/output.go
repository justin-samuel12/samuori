package main

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"os"
	"strings"
	"time"
)

func spdxID(c Component) string {
	sum := sha256.Sum256([]byte(c.Kind + ":" + c.Name + "@" + c.Version))
	return "SPDXRef-Package-" + hex.EncodeToString(sum[:8])
}

func purl(c Component) string {
	if c.Kind == "go" {
		return "pkg:golang/" + c.Name + "@" + c.Version
	}
	return "pkg:npm/" + strings.ReplaceAll(c.Name, "@", "%40") + "@" + c.Version
}

// writeSBOM writes an SPDX 2.3 document listing every shipped component with the license found in its files.
func writeSBOM(path string, comps []Component) error {
	type ref struct {
		Category string `json:"referenceCategory"`
		Type     string `json:"referenceType"`
		Locator  string `json:"referenceLocator"`
	}
	type pkg struct {
		ID         string `json:"SPDXID"`
		Name       string `json:"name"`
		Version    string `json:"versionInfo"`
		Download   string `json:"downloadLocation"`
		Concluded  string `json:"licenseConcluded"`
		Declared   string `json:"licenseDeclared"`
		Copyright  string `json:"copyrightText"`
		FilesAnaly bool   `json:"filesAnalyzed"`
		Refs       []ref  `json:"externalRefs"`
	}
	type rel struct {
		A    string `json:"spdxElementId"`
		Type string `json:"relationshipType"`
		B    string `json:"relatedSpdxElement"`
	}
	doc := map[string]any{
		"spdxVersion": "SPDX-2.3", "dataLicense": "CC0-1.0", "SPDXID": "SPDXRef-DOCUMENT",
		"name":              "samuori dependencies",
		"documentNamespace": "https://samuori.invalid/spdx/" + time.Now().UTC().Format("20060102T150405Z"),
		"creationInfo":      map[string]any{"created": time.Now().UTC().Format(time.RFC3339), "creators": []string{"Tool: samuori-licensecheck"}},
	}
	root := pkg{ID: "SPDXRef-Samuori", Name: "samuori", Version: "NOASSERTION", Download: "NOASSERTION", Concluded: "NOASSERTION", Declared: "NOASSERTION", Copyright: "NOASSERTION", Refs: []ref{}}
	pkgs := []pkg{root}
	rels := []rel{{"SPDXRef-DOCUMENT", "DESCRIBES", root.ID}}
	for _, c := range comps {
		p := pkg{ID: spdxID(c), Name: c.Name, Version: c.Version, Download: "NOASSERTION", Concluded: spdxExpr(c.License), Declared: "NOASSERTION",
			Copyright: "NOASSERTION", Refs: []ref{{"PACKAGE-MANAGER", "purl", purl(c)}}}
		pkgs = append(pkgs, p)
		rels = append(rels, rel{root.ID, "DEPENDS_ON", p.ID})
	}
	doc["packages"], doc["relationships"] = pkgs, rels
	raw, err := json.MarshalIndent(doc, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(path, append(raw, '\n'), 0o644)
}

func spdxExpr(l string) string {
	if l == "" {
		return "NOASSERTION"
	}
	return l
}

// writeNotices concatenates the license and NOTICE files of every shipped component.
func writeNotices(path string, comps []Component) error {
	var b strings.Builder
	b.WriteString("Third-party software in samuori binaries and UI bundle.\n")
	b.WriteString("Generated by tools/licensecheck; do not edit.\n")
	for _, c := range comps {
		fmt.Fprintf(&b, "\n%s\n%s %s (%s)\n%s\n", strings.Repeat("=", 78), c.Name, c.Version, c.License, strings.Repeat("=", 78))
		for _, f := range append(append([]string{}, c.Notices...), c.Files...) {
			text, err := os.ReadFile(f)
			if err != nil {
				return err
			}
			b.Write(text)
			if !strings.HasSuffix(string(text), "\n") {
				b.WriteString("\n")
			}
		}
		if len(c.Files) == 0 {
			b.WriteString("No license file found in the package; see its declared license above.\n")
		}
	}
	return os.WriteFile(path, []byte(b.String()), 0o644)
}
